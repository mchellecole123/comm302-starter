// Helper to generate simulated chart series
function generateSeries(basePrice: number, pointsCount: number, volatility: number, trend: number) {
  const points = [];
  let current = basePrice;
  const now = new Date();
  
  for (let i = 0; i < pointsCount; i++) {
    const change = (Math.random() - 0.48 + trend) * volatility * basePrice;
    current = Math.max(current + change, basePrice * 0.4);
    const d = new Date(now.getTime() - (pointsCount - i) * 60 * 60 * 1000);
    const timeStr = `${d.getHours().toString().padStart(2, '0')}:${d.getMinutes().toString().padStart(2, '0')}`;
    const open = current - (Math.random() - 0.5) * volatility * basePrice * 0.5;
    const close = current;
    const high = Math.max(open, close) + Math.random() * volatility * basePrice * 0.4;
    const low = Math.min(open, close) - Math.random() * volatility * basePrice * 0.4;
    
    points.push({
      time: timeStr,
      price: Number(current.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
    });
  }
  return points;
}

